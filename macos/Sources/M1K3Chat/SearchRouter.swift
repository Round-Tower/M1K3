import Foundation

public enum SearchRouter {
    public enum Verdict: Sendable, Equatable {
        /// Let a web read the picker named run.
        case web
        /// Stable knowledge, conversation or the user's own things: a web read is vetoed.
        case local
    }

    /// The verdict with the score behind it (nil when it couldn't be scored), so a caller can log
    /// what the head saw: those lines are future labels.
    public struct Decision: Sendable, Equatable {
        public let verdict: Verdict
        public let probability: Double?

        public init(verdict: Verdict, probability: Double?) {
            self.verdict = verdict
            self.probability = probability
        }
    }

    /// One logistic layer: P(the turn needs the web) = σ(bias + w · v/|v|). `.web` at or above
    /// `threshold`.
    public struct Head: Sendable, Equatable {
        public let threshold: Double
        public let bias: Double
        public let weights: [Double]

        public init(threshold: Double, bias: Double, weights: [Double]) {
            self.threshold = threshold
            self.bias = bias
            self.weights = weights
        }

        /// The stub the trainer writes before any teacher pass has no weights: it never vetoes.
        public var isTrained: Bool {
            !weights.isEmpty
        }

        public static let shipping = Head(
            threshold: SearchRouterWeights.threshold, bias: SearchRouterWeights.bias, weights: SearchRouterWeights.weights
        )
    }

    /// P(needs the web) for one sentence vector; nil when it can't be scored.
    public static func probability(_ vector: [Double], head: Head = .shipping) -> Double? {
        guard head.isTrained, vector.count == head.weights.count else { return nil }
        let norm = vector.reduce(0) { $0 + $1 * $1 }.squareRoot()
        guard norm > 0, norm.isFinite else { return nil }
        var z = head.bias
        for (value, weight) in zip(vector, head.weights) {
            z += value / norm * weight
        }
        let p = 1 / (1 + exp(-z))
        return p.isFinite ? p : nil
    }

    public static func verdict(probability: Double?, head: Head = .shipping) -> Verdict {
        guard let probability, probability.isFinite else { return .web }
        return probability >= head.threshold ? .web : .local
    }

    public static func decide(for question: String, embed: (String) -> [Double]?, head: Head = .shipping) -> Decision {
        let p = embed(question).flatMap { probability($0, head: head) }
        return Decision(verdict: verdict(probability: p, head: head), probability: p)
    }
}
